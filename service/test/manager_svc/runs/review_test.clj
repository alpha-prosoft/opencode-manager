(defn- temp-dir
  []
  (.toFile (Files/createTempDirectory "review-test" (make-array FileAttribute 0))))

(defn- git!
  [dir & args]
  (let [{:keys [exit err]}
        (apply shell/sh "git" "-c" "user.name=t" "-c" "user.email=t@t" (concat args [:dir (str dir)]))]
    (when-not (zero? exit)
      (throw (ex-info err {:args args})))))

(defn- commit!
  [dir files message]
  (doseq [[path content] files]
    (io/make-parents (io/file dir path))
    (spit (io/file dir path) content))
  (git! dir "add" "-A")
  (git! dir "commit" "-qm" message))

(defn- service-repo
  "main: pricing.py, then a later unrelated commit; feature forks before it and changes pricing.py."
  [dir]
  (.mkdirs (io/file dir))
  (git! dir "init" "-q" "-b" "main")
  (commit! dir {"pricing.py" "def total(p):\n    return sum(p)\n"} "initial")
  (git! dir "checkout" "-q" "-b" "feature")
  (commit! dir {"pricing.py" "def total(p):\n    return sum(p[1:])\n"} "skip the first price")
  (git! dir "checkout" "-q" "main")
  (commit! dir {"README.md" "demo\n"} "readme")
  dir)

(defn- branch-review-context
  [root inputs]
  {:system {:settings {:local-repo-roots [(str root)]}}
   :run {:activity "review" :team-id "alpha"}
   :options {:repository {:url (str "file://" (io/file root "service"))}
             :post-mode "dry-run"
             :max-comments 10}
   :inputs inputs
   :workspace (str (io/file root "workspace"))
   :session-url ""
   :record! (fn [& args] (throw (ex-info "nothing is recorded for a branch review" {:args args})))})

(deftest a-branch-review-diffs-the-branch-against-its-base
  (let [root
        (temp-dir)

        _
        (service-repo (io/file root "service"))

        ctx
        (branch-review-context root {:branch "feature" :base "main"})

        _
        (handlers/prepare! ctx)

        diff
        (handlers/read-context ctx "branch.diff")]
    (testing "only the branch's own change, not what main gained since"
      (is
       (string/includes? diff "+    return sum(p[1:])"))
      (is
       (not (string/includes? diff "README.md"))))
    (is
     (= {"pricing.py" #{1 2}}
        (review/changed-lines diff)))
    (is
     (string/includes? (slurp (io/file (handlers/repo ctx) "pricing.py")) "p[1:]"))
    (is
     (string/includes? (handlers/read-context ctx "branch.md") "- Compared with: main"))
    (is
     (string/starts-with? (handlers/prompt ctx) (str "Review branch `feature` of file://" root "/service against `main`.")))
    (let [result
          (handlers/finalize! ctx {:verdict "REQUEST_CHANGES"
                                   :summary "Drops a price"
                                   :findings [{:severity "major" :title "First price skipped" :body "Off by one"
                                               :path "pricing.py" :line 2}]})]
      (is
       (= {:branch {:name "feature" :base "main"}
           :plan {:mode "dry-run" :comments 2 :inline 1 :folded 0}
           :posted 0}
          (dissoc result :review))))))

(deftest a-branch-without-changes-cannot-be-reviewed
  (let [root
        (temp-dir)

        _
        (service-repo (io/file root "service"))]
    (is
     (thrown-with-msg? clojure.lang.ExceptionInfo #"Branch main has no changes against main"
                       (handlers/prepare! (branch-review-context root {:branch "main" :base "main"}))))))
