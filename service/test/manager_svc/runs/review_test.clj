(def diff
  "diff --git a/a.py b/a.py
index 1..2 100644
--- a/a.py
+++ b/a.py
@@ -1,3 +1,4 @@
 one
-two
+deux
+three
 four
diff --git a/gone.py b/gone.py
--- a/gone.py
+++ /dev/null
@@ -1 +0,0 @@
-bye
")

(deftest changed-lines-are-the-new-side-of-each-hunk
  (is
   (= {"a.py" #{1 2 3 4}}
      (review/changed-lines diff))))

(def submission
  {:verdict "APPROVE_WITH_NITS"
   :summary "Looks fine"
   :findings [{:severity "nit" :title "Naming" :body "Rename" :path "a.py" :line 2}
              {:severity "blocker" :title "Crash" :body "Fix" :path "a.py" :line 3 :suggestion "x = 1"}
              {:severity "minor" :title "Outside" :body "Not in diff" :path "b.py" :line 9}]
   :checked ["tests"]})

(deftest findings-on-changed-lines-become-inline-comments-within-the-budget
  (let [plan
        (review/plan-post submission diff "auto" 2 "https://s.example")

        [summary & inline]
        (:comments plan)]
    (is
     (= [1 2]
        [(:inline-count plan) (:folded-count plan)]))
    (is
     (= [{:key "finding-0" :path "a.py" :line 3 :content "**blocker**: Crash\n\nFix\n\n```\nx = 1\n```"}]
        inline))
    (is
     (= "summary"
        (:key summary)))
    (is
     (string/starts-with? (:content summary) "## Automated review: APPROVE WITH NITS\n\nLooks fine\n\n1 finding(s) are posted as inline comments."))
    (is
     (string/includes? (:content summary) "- **minor** `b.py:9`: Outside"))
    (is
     (string/includes? (:content summary) "<details><summary>Checked and OK</summary>\n\n- tests\n</details>"))
    (is
     (string/ends-with? (:content summary) "_Generated by an OpenCode review session: https://s.example_"))))

