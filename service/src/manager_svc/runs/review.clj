(ns manager-svc.runs.review
  "Turns a submitted review into the comments posted on a pull request: inline
   comments for findings anchored on changed lines (bounded by max-comments),
   everything else folded into one summary comment. Mirrors review_post.py."
  (:require [clojure.string :as string]
            [manager-svc.runs.submissions :as submissions]))

(def ^:private hunk
  #"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")

(defn changed-lines
  "{path #{new-file line numbers}} of lines present in the diff's new side."
  [diff]
  (first
   (reduce
    (fn [[lines path current] raw]
      (cond
        (string/starts-with? raw "+++ ")
        (let [target (string/trim (subs raw 4))]
          [lines
           (when-not (= "/dev/null" target)
             (if (string/starts-with? target "b/") (subs target 2) target))
           current])

        (re-find hunk raw)
        [lines path (parse-long (second (re-find hunk raw)))]

        (or (nil? path)
            (some #(string/starts-with? raw %) ["---" "diff " "index "]))
        [lines path current]

        (or (string/starts-with? raw "+") (string/starts-with? raw " "))
        [(update lines path (fnil conj #{}) current) path (inc current)]

        :else
        [lines path current]))
    [{} nil 0]
    (string/split-lines (or diff "")))))

(defn- finding-markdown
  [{:keys [severity title body path line suggestion]} with-location]
  (str "**" severity "**"
       (when (and with-location path) (str " `" path ":" line "`"))
       ": " title "\n\n" body
       (when suggestion (str "\n\n```\n" suggestion "\n```"))))

(defn plan-post
  "{:mode :comments [{:key :content :path :line}] :inline-count :folded-count}"
  [{:keys [verdict summary findings checked]} diff mode max-comments session-url]
  (let [lines
        (changed-lines diff)

        ordered
        (sort-by #(get submissions/severity-order (:severity %)) findings)

        inline-budget
        (max (dec max-comments) 0)

        [inline folded]
        (reduce
         (fn [[inline folded] [index {:keys [path line] :as finding}]]
           (if (and path line
                    (contains? (get lines path #{}) line)
                    (< (count inline) inline-budget))
             [(conj inline {:key (str "finding-" index)
                            :content (finding-markdown finding false)
                            :path path
                            :line line})
              folded]
             [inline (conj folded finding)]))
         [[] []]
         (map-indexed vector ordered))

        sections
        (cond-> [(str "## Automated review: " (string/replace verdict "_" " "))
                 summary]
          (seq inline)
          (conj (str (count inline) " finding(s) are posted as inline comments."))

          (seq folded)
          (conj (str "### Findings\n\n"
                     (string/join "\n" (for [f folded]
                                         (str "- " (string/replace (finding-markdown f true) "\n" "\n  "))))))

          (seq checked)
          (conj (str "<details><summary>Checked and OK</summary>\n\n"
                     (string/join "\n" (map #(str "- " %) checked))
                     "\n</details>"))

          :always
          (conj (str "_Generated by an OpenCode review session: " session-url "_")))]
    {:mode mode
     :comments (into [{:key "summary" :content (string/join "\n\n" sections)}] inline)
     :inline-count (count inline)
     :folded-count (count folded)}))
