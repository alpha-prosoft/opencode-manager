import re
from typing import Literal

from pydantic import BaseModel, Field

Severity = Literal["blocker", "major", "minor", "question", "nit"]
Verdict = Literal["APPROVE", "APPROVE_WITH_NITS", "REQUEST_CHANGES"]
SEVERITY_ORDER = {"blocker": 0, "major": 1, "minor": 2, "question": 3, "nit": 4}
HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@")


class ReviewFinding(BaseModel):
    severity: Severity
    title: str = Field(max_length=200, description="One-line statement of the problem")
    body: str = Field(max_length=4000, description="Explanation and the concrete fix, in Markdown")
    path: str | None = Field(default=None, description="Repository-relative path of the changed file")
    line: int | None = Field(default=None, ge=1, description="Line number in the NEW version of the file, inside the diff")
    suggestion: str | None = Field(default=None, max_length=4000, description="Replacement code for that line, if any")


class ReviewSubmission(BaseModel):
    verdict: Verdict
    summary: str = Field(max_length=4000)
    findings: list[ReviewFinding] = Field(default=[], max_length=100)
    checked: list[str] = Field(default=[], max_length=50, description="Checklist items verified as OK")


class PlannedComment(BaseModel):
    key: str
    content: str
    path: str | None = None
    line: int | None = None


class PostPlan(BaseModel):
    mode: str
    comments: list[PlannedComment]
    inline_count: int
    folded_count: int


def changed_lines(diff: str) -> dict[str, set[int]]:
    lines: dict[str, set[int]] = {}
    path, current = None, 0
    for raw in diff.splitlines():
        if raw.startswith("+++ "):
            target = raw[4:].strip()
            path = None if target == "/dev/null" else target.removeprefix("b/")
        elif match := HUNK.match(raw):
            current = int(match.group(1))
        elif path is None or raw.startswith(("---", "diff ", "index ")):
            continue
        elif raw.startswith("+") or raw.startswith(" "):
            lines.setdefault(path, set()).add(current)
            current += 1
    return lines


def _finding_markdown(finding: ReviewFinding, with_location: bool) -> str:
    location = f" `{finding.path}:{finding.line}`" if with_location and finding.path else ""
    text = f"**{finding.severity}**{location}: {finding.title}\n\n{finding.body}"
    if finding.suggestion:
        text += f"\n\n```\n{finding.suggestion}\n```"
    return text


def plan_post(review: ReviewSubmission, diff: str, mode: str, max_comments: int, session_url: str) -> PostPlan:
    diff_lines = changed_lines(diff)
    findings = sorted(review.findings, key=lambda f: SEVERITY_ORDER[f.severity])
    inline_budget = max(max_comments - 1, 0)
    inline, folded = [], []
    for index, finding in enumerate(findings):
        anchored = finding.path and finding.line and finding.line in diff_lines.get(finding.path, set())
        if anchored and len(inline) < inline_budget:
            inline.append(
                PlannedComment(
                    key=f"finding-{index}",
                    content=_finding_markdown(finding, with_location=False),
                    path=finding.path,
                    line=finding.line,
                )
            )
        else:
            folded.append(finding)

    sections = [f"## Automated review: {review.verdict.replace('_', ' ')}", review.summary]
    if inline:
        sections.append(f"{len(inline)} finding(s) are posted as inline comments.")
    if folded:
        items = (_finding_markdown(f, True).replace("\n", "\n  ") for f in folded)
        sections.append("### Findings\n\n" + "\n".join(f"- {item}" for item in items))
    if review.checked:
        sections.append("<details><summary>Checked and OK</summary>\n\n" + "\n".join(f"- {c}" for c in review.checked) + "\n</details>")
    sections.append(f"_Generated by an OpenCode review session: {session_url}_")
    summary = PlannedComment(key="summary", content="\n\n".join(sections))
    return PostPlan(mode=mode, comments=[summary, *inline], inline_count=len(inline), folded_count=len(folded))
